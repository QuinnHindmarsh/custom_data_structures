using value_t = std::uint64_t;

constexpr std::size_t N = 1'000'000;
constexpr std::size_t MIXED_OPS = N;
constexpr std::size_t REPS = 3;

// ---------- one interface over both maps ----------

// open_map with a given max load factor (resize factor 2, default hash/eq)
template <typename K, float LF>
using omap = open_map<K, value_t, std::hash<K>, std::equal_to<K>, 2, LF>;

constexpr std::array<float, 5> load_factors{0.70f, 0.75f, 0.80f, 0.85f, 0.90f};
constexpr std::size_t NUM_LF = load_factors.size();
constexpr std::size_t NUM_MAPS = NUM_LF + 1; // every load factor + std::unordered_map (last)
constexpr std::size_t STD = NUM_MAPS - 1;    // index of std::unordered_map

template <typename K, typename H, typename E, int R, float LF>
void map_insert(open_map<K, value_t, H, E, R, LF> &m, const K &k, value_t v) { m.insert(k, v); }
template <typename K>
void map_insert(std::unordered_map<K, value_t> &m, const K &k, value_t v) { m.insert_or_assign(k, v); }

template <typename K, typename H, typename E, int R, float LF>
const value_t *map_find(const open_map<K, value_t, H, E, R, LF> &m, const K &k) { return m.find(k); }
template <typename K>
const value_t *map_find(const std::unordered_map<K, value_t> &m, const K &k)
{
    auto it = m.find(k);
    return it == m.end() ? nullptr : &it->second;
}

template <typename K, typename H, typename E, int R, float LF>
void map_erase(open_map<K, value_t, H, E, R, LF> &m, const K &k) { m.erase(k); }
template <typename K>
void map_erase(std::unordered_map<K, value_t> &m, const K &k) { m.erase(k); }

// ---------- keys ----------

template <typename K>
K make_key(std::uint64_t x);
template <>
std::int32_t make_key<std::int32_t>(std::uint64_t x) { return static_cast<std::int32_t>(x); }
template <>
std::int64_t make_key<std::int64_t>(std::uint64_t x) { return static_cast<std::int64_t>(x); }
template <>
std::string make_key<std::string>(std::uint64_t x) { return "key_" + std::to_string(x); } // ~24 chars, too long for SSO

// ---------- workload: the same keys and ops are fed to every map ----------

enum Phase
{
    INSERT,
    UPDATE,
    FIND_HIT,
    FIND_MISS,
    ERASE_MISS,
    ERASE_HIT,
    MIXED,
    NUM_PHASES
};
constexpr const char *phase_names[NUM_PHASES]{"insert", "update", "find hit", "find miss", "erase miss", "erase hit", "mixed"};

// What the timed loop does. Insert and update both call insert, hit and miss both call find / erase,
// so the loop only branches three ways. The finer split only matters when generating the stream.
enum class OpKind : std::uint8_t
{
    Insert, // insert + update
    Find,   // find hit + find miss
    Erase   // erase hit + erase miss
};

struct Op
{
    OpKind kind;
    std::uint32_t key_idx; // index into Workload::keys
};

template <typename K>
struct Workload
{
    // keys[0, N)           present: inserted by the phases and pre-filled for mixed
    // keys[N, 2N)          absent: never inserted, used for every miss
    // keys[2N, 2N + N/4)   fresh: inserted for the first time by mixed
    std::vector<K> keys;
    std::vector<std::uint32_t> present_shuffled; // indices of present keys, different order to insertion
    std::vector<Op> mixed;
    std::size_t mixed_find_hits = 0; // how many mixed finds must return a value
};

template <typename K>
Workload<K> make_workload(std::uint64_t seed)
{
    std::mt19937_64 rng{seed};

    constexpr std::size_t quarter = MIXED_OPS / 4;
    constexpr std::size_t present_begin = 0, absent_begin = N, fresh_begin = 2 * N;

    Workload<K> w;
    {
        std::unordered_set<K> seen;
        w.keys.reserve(fresh_begin + quarter);
        while (w.keys.size() < fresh_begin + quarter)
        {
            K k = make_key<K>(rng());
            if (seen.insert(k).second)
                w.keys.push_back(std::move(k));
        }
    }

    w.present_shuffled.resize(N);
    for (std::uint32_t i = 0; i < N; ++i)
        w.present_shuffled[i] = i;
    std::shuffle(w.present_shuffled.begin(), w.present_shuffled.end(), rng);

    // exact 25/25/25/25 split, finds and erases each split 50/50 hit/miss, in random order
    enum Gen : std::uint8_t { G_INSERT, G_UPDATE, G_FIND_HIT, G_FIND_MISS, G_ERASE_HIT, G_ERASE_MISS };
    std::vector<Gen> kinds;
    kinds.reserve(MIXED_OPS);
    kinds.insert(kinds.end(), quarter, G_INSERT);
    kinds.insert(kinds.end(), quarter, G_UPDATE);
    kinds.insert(kinds.end(), quarter / 2, G_FIND_HIT);
    kinds.insert(kinds.end(), quarter - quarter / 2, G_FIND_MISS);
    kinds.insert(kinds.end(), quarter / 2, G_ERASE_HIT);
    kinds.insert(kinds.end(), quarter - quarter / 2, G_ERASE_MISS);
    std::shuffle(kinds.begin(), kinds.end(), rng);

    // simulate the map's contents so every op targets the right kind of key
    std::vector<std::uint32_t> live(N);
    for (std::uint32_t i = 0; i < N; ++i)
        live[i] = static_cast<std::uint32_t>(present_begin + i);
    std::uint32_t next_fresh = static_cast<std::uint32_t>(fresh_begin);
    std::uniform_int_distribution<std::uint32_t> absent_dist(absent_begin, fresh_begin - 1);

    auto random_live = [&]() -> std::size_t
    { return std::uniform_int_distribution<std::size_t>(0, live.size() - 1)(rng); };

    w.mixed.reserve(MIXED_OPS);
    for (Gen g : kinds)
    {
        switch (g)
        {
        case G_INSERT:
            live.push_back(next_fresh);
            w.mixed.push_back({OpKind::Insert, next_fresh++});
            break;
        case G_UPDATE:
            w.mixed.push_back({OpKind::Insert, live[random_live()]});
            break;
        case G_FIND_HIT:
            w.mixed.push_back({OpKind::Find, live[random_live()]});
            ++w.mixed_find_hits;
            break;
        case G_FIND_MISS:
            w.mixed.push_back({OpKind::Find, absent_dist(rng)});
            break;
        case G_ERASE_HIT:
        {
            const std::size_t i = random_live();
            w.mixed.push_back({OpKind::Erase, live[i]});
            live[i] = live.back(); // swap-remove, order of live doesn't matter
            live.pop_back();
            break;
        }
        case G_ERASE_MISS:
            w.mixed.push_back({OpKind::Erase, absent_dist(rng)});
            break;
        }
    }
    return w;
}

// ---------- running ----------

using Times = std::array<double, NUM_PHASES>; // seconds per phase

struct Check
{
    std::uint64_t checksum = 0;    // sum of every value found, must match across maps
    bool mixed_hits_ok = true;     // mixed finds hit exactly as often as expected
};

template <typename Fn>
double time_it(Fn fn)
{
    Timer t;
    fn();
    return t.elapsed();
}

template <typename Map, typename K>
Times run_once(const Workload<K> &w, Check &check)
{
    Times t{};
    const auto &keys = w.keys;
    std::uint64_t &sum = check.checksum;

    {
        Map m;
        t[INSERT] = time_it([&]
                            { for (std::size_t i = 0; i < N; ++i) map_insert(m, keys[i], i); });
        t[UPDATE] = time_it([&]
                            { for (std::size_t i = 0; i < N; ++i) map_insert(m, keys[i], i + 1); });
        t[FIND_HIT] = time_it([&]
                              { for (std::uint32_t i : w.present_shuffled)
                                    if (const value_t *p = map_find(m, keys[i])) sum += *p; });
        t[FIND_MISS] = time_it([&]
                               { for (std::size_t i = N; i < 2 * N; ++i)
                                     if (const value_t *p = map_find(m, keys[i])) sum += *p; }); // never hits if the map is correct
        t[ERASE_MISS] = time_it([&]
                                { for (std::size_t i = N; i < 2 * N; ++i) map_erase(m, keys[i]); });
        t[ERASE_HIT] = time_it([&]
                               { for (std::uint32_t i : w.present_shuffled) map_erase(m, keys[i]); });
    }

    {
        Map m;
        for (std::size_t i = 0; i < N; ++i) // untimed setup
            map_insert(m, keys[i], i);

        std::size_t hits = 0;
        t[MIXED] = time_it([&]
                           {
                               value_t v = 0;
                               for (const Op &op : w.mixed)
                               {
                                   const K &k = keys[op.key_idx];
                                   switch (op.kind)
                                   {
                                   case OpKind::Insert:
                                       map_insert(m, k, ++v);
                                       break;
                                   case OpKind::Find:
                                       if (const value_t *p = map_find(m, k))
                                       {
                                           sum += *p;
                                           ++hits;
                                       }
                                       break;
                                   case OpKind::Erase:
                                       map_erase(m, k);
                                       break;
                                   }
                               } });
        check.mixed_hits_ok = check.mixed_hits_ok && hits == w.mixed_find_hits;
    }
    return t;
}

// Runs one map type once and keeps the best time per phase.
template <typename Map, typename K>
void run_into(const Workload<K> &w, Times &best, Check &check)
{
    const Times t = run_once<Map>(w, check);
    for (int p = 0; p < NUM_PHASES; ++p)
        best[p] = std::min(best[p], t[p]);
}

// Runs open_map once for every load factor in load_factors.
template <typename K, std::size_t... I>
void run_all_load_factors(const Workload<K> &w, std::array<Times, NUM_MAPS> &best,
                          std::array<Check, NUM_MAPS> &checks, std::index_sequence<I...>)
{
    (run_into<omap<K, load_factors[I]>>(w, best[I], checks[I]), ...);
}

// ---------- markdown output ----------

std::string with_commas(std::size_t n) // 1000000 -> "1,000,000"
{
    std::string s = std::to_string(n);
    for (int i = static_cast<int>(s.size()) - 3; i > 0; i -= 3)
        s.insert(static_cast<std::size_t>(i), ",");
    return s;
}

struct Result
{
    std::string key_name;
    std::array<double, NUM_PHASES> speedup; // unordered_map time / fastest open_map time
    std::string table;                      // markdown section with every time
    bool ok;
};

template <typename K>
Result bench(const char *key_name)
{
    std::printf("%-12s generating keys... ", key_name);
    std::fflush(stdout);
    const Workload<K> w = make_workload<K>(12345);

    std::array<Times, NUM_MAPS> best;
    for (Times &t : best)
        t.fill(std::numeric_limits<double>::infinity());
    std::array<Check, NUM_MAPS> checks{};

    for (std::size_t r = 0; r < REPS; ++r) // interleave so all maps see the same machine state
    {
        std::printf("run %zu/%zu... ", r + 1, REPS);
        std::fflush(stdout);
        run_all_load_factors(w, best, checks, std::make_index_sequence<NUM_LF>{});
        run_into<std::unordered_map<K, value_t>>(w, best[STD], checks[STD]);
    }

    Result res{key_name, {}, {}, true};
    for (std::size_t i = 0; i < NUM_MAPS; ++i)
        res.ok = res.ok && checks[i].checksum == checks[STD].checksum && checks[i].mixed_hits_ok;

    std::string &md = res.table;
    md += std::format("### {} keys, N = {}\n\n", key_name, with_commas(N));
    md += std::format("Best of {} runs. Correctness check: {}\n\n", REPS, res.ok ? "OK" : "**FAILED**");

    md += "| phase |";
    for (float lf : load_factors)
        md += std::format(" lf {:.2f} |", lf);
    md += " unordered_map | speedup |\n|:--|";
    for (std::size_t i = 0; i < NUM_MAPS + 1; ++i)
        md += "--:|";
    md += "\n";

    for (int p = 0; p < NUM_PHASES; ++p)
    {
        const double ops = static_cast<double>(p == MIXED ? MIXED_OPS : N);
        std::size_t best_lf = 0;
        for (std::size_t i = 1; i < NUM_LF; ++i)
            if (best[i][p] < best[best_lf][p])
                best_lf = i;

        md += std::format("| {} |", phase_names[p]);
        for (std::size_t i = 0; i < NUM_LF; ++i)
        {
            const double ns = best[i][p] * 1e9 / ops;
            md += i == best_lf ? std::format(" **{:.1f}** |", ns) : std::format(" {:.1f} |", ns);
        }
        res.speedup[p] = best[STD][p] / best[best_lf][p];
        md += std::format(" {:.1f} | {:.2f}x |\n", best[STD][p] * 1e9 / ops, res.speedup[p]);
    }
    md += "\n";

    std::printf("done%s\n", res.ok ? "" : "  CORRECTNESS CHECK FAILED");
    return res;
}

std::string build_markdown(const std::vector<Result> &results)
{
    std::string md = "# open_map benchmark results\n\n";

    char date[32];
    const std::time_t now = std::time(nullptr);
    std::strftime(date, sizeof date, "%Y-%m-%d %H:%M", std::localtime(&now));
    md += std::format("- Run: {}\n", date);
#ifdef __VERSION__
    md += std::format("- Compiler: {}\n", __VERSION__);
#endif
#ifdef __OPTIMIZE__
    md += "- Optimised build: yes\n";
#else
    md += "- Optimised build: **NO, these numbers are meaningless. Build with -O2.**\n";
#endif
#ifdef NDEBUG
    md += "- Asserts: off\n";
#else
    md += "- Asserts: on (build with -DNDEBUG)\n";
#endif
    md += std::format("- N = {} keys per type, mixed = {} ops\n\n", with_commas(N), with_commas(MIXED_OPS));

    md += "## Summary: fastest open_map vs std::unordered_map\n\n";
    md += "Speedup = unordered_map time / time of the fastest open_map load factor. "
          "Above 1x means open_map is faster. **Bold** = open_map is slower.\n\n";
    md += "| keys |";
    for (const char *name : phase_names)
        md += std::format(" {} |", name);
    md += "\n|:--|";
    for (int p = 0; p < NUM_PHASES; ++p)
        md += "--:|";
    md += "\n";
    for (const Result &r : results)
    {
        md += std::format("| {} |", r.key_name);
        for (double s : r.speedup)
            md += s < 1.0 ? std::format(" **{:.2f}x** |", s) : std::format(" {:.2f}x |", s);
        md += "\n";
    }

    md += "\n## Details\n\n";
    md += "Time per operation in ns, lower is better. **Bold** = fastest open_map load factor. "
          "Speedup = unordered_map / fastest open_map.\n\n";
    md += "Phases: **insert** N new keys into an empty map. **update** the same keys again. "
          "**find hit / miss** look up present / absent keys. **erase miss** erase absent keys. "
          "**erase hit** erase every key. **mixed** N random ops on a map holding N keys: "
          "25% insert (new key), 25% update (live key), 25% find (half hit, half miss), "
          "25% erase (half hit, half miss).\n\n";
    for (const Result &r : results)
        md += r.table;
    return md;
}

int main(int argc, char **argv)
{
    const std::string out_path = argc > 1 ? argv[1] : "custom_data_structures\\hashmap\\open_map\\open_map_benchmark_results.md";

    std::vector<Result> results;
    results.push_back(bench<std::int32_t>("int32_t"));
    results.push_back(bench<std::int64_t>("int64_t"));
    results.push_back(bench<std::string>("std::string"));

    std::ofstream out{out_path};
    if (!out)
    {
        std::fprintf(stderr, "could not open %s for writing\n", out_path.c_str());
        return 1;
    }
    out << build_markdown(results);
    std::printf("\nwrote %s\n", out_path.c_str());
    return 0;
}
