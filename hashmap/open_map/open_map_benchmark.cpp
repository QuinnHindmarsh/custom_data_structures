// Benchmark: open_map vs std::unordered_map, using Google Benchmark.
//
// Key types: int32_t, int64_t, std::string. The map always holds about N = 1,000,000 keys
// (or -DBENCH_N=... at build time). One benchmark iteration = one phase = N ops.
// "per_op" is the time of one op. The Time column is one iteration (all N ops).
//
// Phases (every phase is N ops):
//   insert      N new keys into an empty map (includes all rehashes)
//   update      the same N keys again (key already present, value overwritten)
//   find hit    N lookups of present keys, shuffled order
//   find miss   N lookups of keys that are not in the map
//   erase miss  N erases of keys that are not in the map (map is unchanged)
//   erase hit   erase all N keys, shuffled order (map is now empty)
//   mixed       N random ops on a fresh map pre-filled with N keys (fill is untimed):
//                 25% insert  (key is new)
//                 25% update  (key is currently in the map)
//                 25% find    (half hits, half misses)
//                 25% erase   (half hits, half misses)
//               The map grows from 1.000M to 1.125M keys during the phase, then is thrown away.
//               The op stream is generated by simulating the map, so "insert" is always a new key,
//               "update" / "hit" always a live key, and "miss" always an absent key.
// Any map a phase needs (empty, or filled with N keys) is built untimed, and destroyed untimed.
//
// Each key type runs open_map at its best load factor (BEST_LF_* below) vs unordered_map.
// The best load factors came from an earlier sweep of 0.70 .. 0.90, see "historical results/".
//
// Benchmarks are named <phase>/<key type>/<map>, so the two maps sit next to each other.
//
// Correctness: before any timing, main() runs every phase once on both maps and compares a checksum
// of every value found, and checks the mixed phase hits exactly as often as expected. If either is
// off it prints which and exits with 1, because a wrong map's timings mean nothing.
//
// Build (needs Google Benchmark installed, see README.md):
//   g++ -std=c++23 -O2 -DNDEBUG open_map_benchmark.cpp -o open_map_benchmark.exe -lbenchmark -lshlwapi
//   (-lshlwapi is Windows only. On Linux use -lbenchmark -lpthread.)
//
// Full run, median of 20 repetitions, the two maps' repetitions interleaved so noise hits both,
// results also saved as JSON:
//   ./open_map_benchmark.exe --benchmark_repetitions=20 --benchmark_report_aggregates_only=true
//                            --benchmark_enable_random_interleaving=true
//                            --benchmark_out=open_map_results.json --benchmark_out_format=json
// Quick check that everything runs:
//   ./open_map_benchmark.exe --benchmark_min_time=0.01s

#include "open_map.h"

#include <benchmark/benchmark.h>

#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <format>
#include <optional>
#include <random>
#include <string>
#include <unordered_map>
#include <unordered_set>
#include <utility>
#include <vector>

using value_t = std::uint64_t;

#ifndef BENCH_N
#define BENCH_N 1'000'000
#endif
constexpr std::size_t N = BENCH_N; // keys in the map, and ops per phase

// best load factor per key type, from the earlier sweep
constexpr float BEST_LF_INT32 = 0.75f;
constexpr float BEST_LF_INT64 = 0.75f;
constexpr float BEST_LF_STRING = 0.80f;

// ---------- one interface over both maps ----------

// open_map with a given max load factor (resize factor 2, default hash/eq)
template <typename K, float LF>
using omap = open_map<K, value_t, std::hash<K>, std::equal_to<K>, 2, LF>;

template <typename K>
using umap = std::unordered_map<K, value_t>;

template <typename K, typename H, typename E, int R, float LF>
void map_insert(open_map<K, value_t, H, E, R, LF> &m, const K &k, value_t v) { m.insert(k, v); }
template <typename K>
void map_insert(umap<K> &m, const K &k, value_t v) { m.insert_or_assign(k, v); }

template <typename K, typename H, typename E, int R, float LF>
const value_t *map_find(const open_map<K, value_t, H, E, R, LF> &m, const K &k) { return m.find(k); }
template <typename K>
const value_t *map_find(const umap<K> &m, const K &k)
{
    auto it = m.find(k);
    return it == m.end() ? nullptr : &it->second;
}

template <typename K, typename H, typename E, int R, float LF>
void map_erase(open_map<K, value_t, H, E, R, LF> &m, const K &k) { m.erase(k); }
template <typename K>
void map_erase(umap<K> &m, const K &k) { m.erase(k); }

// ---------- keys ----------

template <typename K>
K make_key(std::uint64_t x);
template <>
std::int32_t make_key<std::int32_t>(std::uint64_t x) { return static_cast<std::int32_t>(x); }
template <>
std::int64_t make_key<std::int64_t>(std::uint64_t x) { return static_cast<std::int64_t>(x); }
template <>
std::string make_key<std::string>(std::uint64_t x) { return "key_" + std::to_string(x); } // ~24 chars, too long for SSO

// ---------- workload: the same keys and ops are fed to every map ----------

enum Phase
{
    INSERT,
    UPDATE,
    FIND_HIT,
    FIND_MISS,
    ERASE_MISS,
    ERASE_HIT,
    MIXED,
    NUM_PHASES
};
constexpr const char *phase_names[NUM_PHASES]{"insert", "update", "find hit", "find miss", "erase miss", "erase hit", "mixed"};

// What the timed loop does. Insert and update both call insert, hit and miss both call find / erase,
// so the loop only branches three ways. The finer split only matters when generating the stream.
enum class OpKind : std::uint8_t
{
    Insert, // insert + update
    Find,   // find hit + find miss
    Erase   // erase hit + erase miss
};

// Keys are stored by value (not as an index into Workload::keys) so the timed loops read them
// sequentially. An index would add a random read of the key array to every op, which is a cache
// miss that has nothing to do with the map being measured.
template <typename K>
struct Op
{
    OpKind kind;
    K key;
};

template <typename K>
struct Workload
{
    // keys[0, N)           present: inserted by the phases and pre-filled for mixed
    // keys[N, 2N)          absent: never inserted, used for every miss
    // keys[2N, 2N + N/4)   fresh: inserted for the first time by mixed
    std::vector<K> keys;
    std::vector<K> present_shuffled; // copies of the present keys, different order to insertion
    std::vector<Op<K>> mixed;        // N ops, replayed on a freshly filled map every pass
    std::size_t mixed_find_hits = 0; // how many mixed finds must return a value per pass
};

template <typename K>
Workload<K> make_workload(std::uint64_t seed)
{
    std::mt19937_64 rng{seed};

    constexpr std::size_t quarter = N / 4;
    constexpr std::size_t present_begin = 0, absent_begin = N, fresh_begin = 2 * N;

    Workload<K> w;
    {
        std::unordered_set<K> seen;
        w.keys.reserve(fresh_begin + quarter);
        while (w.keys.size() < fresh_begin + quarter)
        {
            K k = make_key<K>(rng());
            if (seen.insert(k).second)
                w.keys.push_back(std::move(k));
        }
    }

    w.present_shuffled.assign(w.keys.begin() + present_begin, w.keys.begin() + absent_begin);
    std::shuffle(w.present_shuffled.begin(), w.present_shuffled.end(), rng);

    // exact 25/25/25/25 split, finds and erases each split 50/50 hit/miss, in random order
    enum Gen : std::uint8_t
    {
        G_INSERT,
        G_UPDATE,
        G_FIND_HIT,
        G_FIND_MISS,
        G_ERASE_HIT,
        G_ERASE_MISS
    };
    std::vector<Gen> kinds;
    kinds.reserve(N);
    kinds.insert(kinds.end(), quarter, G_INSERT);
    kinds.insert(kinds.end(), quarter, G_UPDATE);
    kinds.insert(kinds.end(), quarter / 2, G_FIND_HIT);
    kinds.insert(kinds.end(), quarter - quarter / 2, G_FIND_MISS);
    kinds.insert(kinds.end(), quarter / 2, G_ERASE_HIT);
    kinds.insert(kinds.end(), quarter - quarter / 2, G_ERASE_MISS);
    std::shuffle(kinds.begin(), kinds.end(), rng);

    // simulate the map's contents so every op targets the right kind of key
    std::vector<std::size_t> live(N);
    for (std::size_t i = 0; i < N; ++i)
        live[i] = present_begin + i;
    std::size_t next_fresh = fresh_begin;
    std::uniform_int_distribution<std::size_t> absent_dist(absent_begin, fresh_begin - 1);

    auto random_live = [&]() -> std::size_t
    { return std::uniform_int_distribution<std::size_t>(0, live.size() - 1)(rng); };

    w.mixed.reserve(N);
    auto push = [&](OpKind kind, std::size_t idx)
    { w.mixed.push_back({kind, w.keys[idx]}); };

    for (Gen g : kinds)
    {
        switch (g)
        {
        case G_INSERT:
            live.push_back(next_fresh);
            push(OpKind::Insert, next_fresh++);
            break;
        case G_UPDATE:
            push(OpKind::Insert, live[random_live()]);
            break;
        case G_FIND_HIT:
            push(OpKind::Find, live[random_live()]);
            ++w.mixed_find_hits;
            break;
        case G_FIND_MISS:
            push(OpKind::Find, absent_dist(rng));
            break;
        case G_ERASE_HIT:
        {
            const std::size_t i = random_live();
            push(OpKind::Erase, live[i]);
            live[i] = live.back(); // swap-remove, order of live doesn't matter
            live.pop_back();
            break;
        }
        case G_ERASE_MISS:
            push(OpKind::Erase, absent_dist(rng));
            break;
        }
    }
    return w;
}

// The workload for key type K, built once (untimed) the first time it's needed.
template <typename K>
const Workload<K> &workload()
{
    static const Workload<K> w = make_workload<K>(42);
    return w;
}

// ---------- the phases ----------
// Each returns the sum of every value it found, used for the correctness check and to stop the
// compiler deleting finds whose result is never used.

template <typename Map, typename K>
void fill(Map &m, const Workload<K> &w, value_t offset = 0)
{
    for (std::size_t i = 0; i < N; ++i)
        map_insert(m, w.keys[i], i + offset);
}

template <typename Map, typename K>
std::uint64_t find_hit(const Map &m, const Workload<K> &w)
{
    std::uint64_t sum = 0;
    for (const K &k : w.present_shuffled)
        if (const value_t *p = map_find(m, k))
            sum += *p;
    return sum;
}

template <typename Map, typename K>
std::uint64_t find_miss(const Map &m, const Workload<K> &w)
{
    std::uint64_t sum = 0;
    for (std::size_t i = N; i < 2 * N; ++i)
        if (const value_t *p = map_find(m, w.keys[i])) // never hits if the map is correct
            sum += *p;
    return sum;
}

template <typename Map, typename K>
void erase_miss(Map &m, const Workload<K> &w)
{
    for (std::size_t i = N; i < 2 * N; ++i)
        map_erase(m, w.keys[i]);
}

template <typename Map, typename K>
void erase_hit(Map &m, const Workload<K> &w)
{
    for (const K &k : w.present_shuffled)
        map_erase(m, k);
}

struct MixedResult
{
    std::uint64_t sum = 0;
    std::size_t hits = 0;
};

template <typename Map, typename K>
MixedResult mixed(Map &m, const Workload<K> &w)
{
    MixedResult r;
    value_t v = 0;
    for (const Op<K> &op : w.mixed)
    {
        switch (op.kind)
        {
        case OpKind::Insert:
            map_insert(m, op.key, ++v);
            break;
        case OpKind::Find:
            if (const value_t *p = map_find(m, op.key))
            {
                r.sum += *p;
                ++r.hits;
            }
            break;
        case OpKind::Erase:
            map_erase(m, op.key);
            break;
        }
    }
    return r;
}

// ---------- correctness check (runs once, before any timing) ----------

struct Check
{
    std::uint64_t sum = 0;
    bool mixed_hits_ok = true;
};

// One pass of every phase on map type Map.
template <typename Map, typename K>
Check check_pass(const Workload<K> &w)
{
    Check c;
    {
        Map m;
        fill(m, w);
        fill(m, w, 1); // update
        c.sum += find_hit(m, w);
        c.sum += find_miss(m, w);
        erase_miss(m, w);
        erase_hit(m, w);
        c.sum += find_hit(m, w); // map is empty now, so this must add 0
    }
    {
        Map m;
        fill(m, w);
        const MixedResult r = mixed(m, w);
        c.sum += r.sum;
        c.mixed_hits_ok = r.hits == w.mixed_find_hits;
    }
    return c;
}

template <typename K, float LF>
bool check(const char *key_name)
{
    const Workload<K> &w = workload<K>();
    const Check a = check_pass<omap<K, LF>>(w);
    const Check b = check_pass<umap<K>>(w);
    const bool ok = a.sum == b.sum && a.mixed_hits_ok && b.mixed_hits_ok;
    std::printf("correctness check %-12s %s\n", key_name, ok ? "OK" : "FAILED");
    if (a.sum != b.sum)
        std::printf("  checksum differs: open_map %llu, unordered_map %llu\n",
                    static_cast<unsigned long long>(a.sum), static_cast<unsigned long long>(b.sum));
    if (!a.mixed_hits_ok)
        std::printf("  open_map: mixed finds hit the wrong number of times\n");
    if (!b.mixed_hits_ok)
        std::printf("  unordered_map: mixed finds hit the wrong number of times\n");
    return ok;
}

// ---------- benchmarks ----------
// Building and destroying maps runs inside PauseTiming / ResumeTiming, so it is not timed.
// That pause costs well under a microsecond, which is nothing next to N ops.

void report_per_op(benchmark::State &st)
{
    st.counters["per_op"] = benchmark::Counter(static_cast<double>(N),
                                               benchmark::Counter::kIsIterationInvariantRate | benchmark::Counter::kInvert);
}

template <typename Map, typename K>
void BM_insert(benchmark::State &st)
{
    const Workload<K> &w = workload<K>();
    std::optional<Map> m;
    for (auto _ : st)
    {
        st.PauseTiming();
        m.emplace();
        st.ResumeTiming();

        fill(*m, w);
        benchmark::ClobberMemory();

        st.PauseTiming();
        m.reset();
        st.ResumeTiming();
    }
    report_per_op(st);
}

template <typename Map, typename K>
void BM_update(benchmark::State &st)
{
    const Workload<K> &w = workload<K>();
    Map m;
    fill(m, w); // update keeps the same keys, so one fill serves every iteration
    value_t offset = 0;
    for (auto _ : st)
    {
        fill(m, w, ++offset);
        benchmark::ClobberMemory();
    }
    report_per_op(st);
}

template <typename Map, typename K>
void BM_find_hit(benchmark::State &st)
{
    const Workload<K> &w = workload<K>();
    Map m;
    fill(m, w);
    for (auto _ : st)
        benchmark::DoNotOptimize(find_hit(m, w));
    report_per_op(st);
}

template <typename Map, typename K>
void BM_find_miss(benchmark::State &st)
{
    const Workload<K> &w = workload<K>();
    Map m;
    fill(m, w);
    for (auto _ : st)
        benchmark::DoNotOptimize(find_miss(m, w));
    report_per_op(st);
}

template <typename Map, typename K>
void BM_erase_miss(benchmark::State &st)
{
    const Workload<K> &w = workload<K>();
    Map m;
    fill(m, w); // erasing absent keys leaves the map as it was
    for (auto _ : st)
    {
        erase_miss(m, w);
        benchmark::ClobberMemory();
    }
    report_per_op(st);
}

template <typename Map, typename K>
void BM_erase_hit(benchmark::State &st)
{
    const Workload<K> &w = workload<K>();
    std::optional<Map> m;
    for (auto _ : st)
    {
        st.PauseTiming();
        m.emplace();
        fill(*m, w);
        st.ResumeTiming();

        erase_hit(*m, w);
        benchmark::ClobberMemory();

        st.PauseTiming();
        m.reset();
        st.ResumeTiming();
    }
    report_per_op(st);
}

template <typename Map, typename K>
void BM_mixed(benchmark::State &st)
{
    const Workload<K> &w = workload<K>();
    std::optional<Map> m;
    for (auto _ : st)
    {
        st.PauseTiming();
        m.emplace();
        fill(*m, w);
        st.ResumeTiming();

        benchmark::DoNotOptimize(mixed(*m, w));

        st.PauseTiming();
        m.reset();
        st.ResumeTiming();
    }
    report_per_op(st);
}

// ---------- registration and main ----------

using BenchFn = void (*)(benchmark::State &);

void add(const char *phase, const char *key_name, const std::string &map_name, BenchFn fn)
{
    const std::string name = std::string{phase} + "/" + key_name + "/" + map_name;
    benchmark::RegisterBenchmark(name.c_str(), fn)->Unit(benchmark::kMillisecond);
}

// Registers every phase for key type K, open_map then unordered_map for each phase.
template <typename K, float LF>
void add_all(const char *k)
{
    using O = omap<K, LF>;
    using U = umap<K>;
    const std::string o = std::format("open_map(lf {:.2f})", LF);
    const std::string u = "unordered_map";

    add(phase_names[INSERT], k, o, BM_insert<O, K>);
    add(phase_names[INSERT], k, u, BM_insert<U, K>);
    add(phase_names[UPDATE], k, o, BM_update<O, K>);
    add(phase_names[UPDATE], k, u, BM_update<U, K>);
    add(phase_names[FIND_HIT], k, o, BM_find_hit<O, K>);
    add(phase_names[FIND_HIT], k, u, BM_find_hit<U, K>);
    add(phase_names[FIND_MISS], k, o, BM_find_miss<O, K>);
    add(phase_names[FIND_MISS], k, u, BM_find_miss<U, K>);
    add(phase_names[ERASE_MISS], k, o, BM_erase_miss<O, K>);
    add(phase_names[ERASE_MISS], k, u, BM_erase_miss<U, K>);
    add(phase_names[ERASE_HIT], k, o, BM_erase_hit<O, K>);
    add(phase_names[ERASE_HIT], k, u, BM_erase_hit<U, K>);
    add(phase_names[MIXED], k, o, BM_mixed<O, K>);
    add(phase_names[MIXED], k, u, BM_mixed<U, K>);
}

int main(int argc, char **argv)
{
    benchmark::Initialize(&argc, argv);
    if (benchmark::ReportUnrecognizedArguments(argc, argv))
        return 1;

    // Builds each key type's workload (a few seconds for strings), then checks both maps agree.
    bool ok = check<std::int32_t, BEST_LF_INT32>("int32_t");
    ok = check<std::int64_t, BEST_LF_INT64>("int64_t") && ok;
    ok = check<std::string, BEST_LF_STRING>("std::string") && ok;
    if (!ok)
        return 1;

    add_all<std::int32_t, BEST_LF_INT32>("int32_t");
    add_all<std::int64_t, BEST_LF_INT64>("int64_t");
    add_all<std::string, BEST_LF_STRING>("std::string");

    benchmark::RunSpecifiedBenchmarks();
    benchmark::Shutdown();
    return 0;
}
