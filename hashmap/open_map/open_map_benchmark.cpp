// Benchmark: open_map vs std::unordered_map.
//
// open_map is run once per max load factor (0.70, 0.75, 0.80, 0.85, 0.90), so each table shows which one is fastest.
//
// Key types: int32_t, int64_t, std::string. N = 1,000,000 keys each.
//
// Phases (each on N keys):
//   insert      N new keys into an empty map (includes all rehashes)
//   update      the same N keys again (key already present, value overwritten)
//   find hit    N lookups of present keys, shuffled order
//   find miss   N lookups of keys that are not in the map
//   erase miss  N erases of keys that are not in the map (map is unchanged)
//   erase hit   erase all N keys, shuffled order
//   mixed       N random ops on a map pre-filled with N keys (fill is untimed):
//                 25% insert  (key is new)
//                 25% update  (key is currently in the map)
//                 25% find    (half hits, half misses)
//                 25% erase   (half hits, half misses)
//               The op stream is generated by simulating the map, so "insert" is always a new key,
//               "update" / "hit" always a live key, and "miss" always an absent key.
//
// Each measurement is repeated 3 times and the BEST time is reported (least noise).
// A checksum of every value found is compared across maps, and the mixed phase also checks that
// exactly the expected number of finds hit. If either is off, a map is returning wrong results.
//
// Build with optimisation, -O0 numbers are meaningless (or use the "build open_map_benchmark (release)" VS Code task):
//   g++ -std=c++23 -O2 -DNDEBUG open_map_benchmark.cpp -o open_map_benchmark
// Run:
//   ./open_map_benchmark                 writes open_map_benchmark_results.md
//   ./open_map_benchmark <file.md>       writes to <file.md>

