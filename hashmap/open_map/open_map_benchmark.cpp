using value_t = std::uint64_t;

constexpr std::size_t N = 1'000'000; // keys in the map, and ops per pease per pass

constexpr std::size_t OPS_INTEGRAL = 100'000'000; // ops per phase
constexpr std::size_t OPS_STRING = 50'000'000;

// best load factor per key type, from the earlier sweep
constexpr float BEST_LF_INT32 = 0.75f;
constexpr float BEST_LF_INT64 = 0.75f;
constexpr float BEST_LF_STRING = 0.80f;

// ---------- one interface over both maps ----------

// open_map with a given max load factor (resize factor 2, default hash/eq)
template <typename K, float LF>
using omap = open_map<K, value_t, std::hash<K>, std::equal_to<K>, 2, LF>;

template <typename K>
using umap = std::unordered_map<K, value_t>;

template <typename K, typename H, typename E, int R, float LF>
void map_insert(open_map<K, value_t, H, E, R, LF> &m, const K &k, value_t v) { m.insert(k, v); }
template <typename K>
void map_insert(umap<K> &m, const K &k, value_t v) { m.insert_or_assign(k, v); }

template <typename K, typename H, typename E, int R, float LF>
const value_t *map_find(const open_map<K, value_t, H, E, R, LF> &m, const K &k) { return m.find(k); }
template <typename K>
const value_t *map_find(const umap<K> &m, const K &k)
{
    auto it = m.find(k);
    return it == m.end() ? nullptr : &it->second;
}

template <typename K, typename H, typename E, int R, float LF>
void map_erase(open_map<K, value_t, H, E, R, LF> &m, const K &k) { m.erase(k); }
template <typename K>
void map_erase(umap<K> &m, const K &k) { m.erase(k); }

// ---------- keys ----------

template <typename K>
K make_key(std::uint64_t x);
template <>
std::int32_t make_key<std::int32_t>(std::uint64_t x) { return static_cast<std::int32_t>(x); }
template <>
std::int64_t make_key<std::int64_t>(std::uint64_t x) { return static_cast<std::int64_t>(x); }
template <>
std::string make_key<std::string>(std::uint64_t x) { return "key_" + std::to_string(x); } // ~24 chars, too long for SSO

// ---------- workload: the same keys and ops are fed to every map ----------

enum Phase
{
    INSERT,
    UPDATE,
    FIND_HIT,
    FIND_MISS,
    ERASE_MISS,
    ERASE_HIT,
    MIXED,
    NUM_PHASES
};
constexpr const char *phase_names[NUM_PHASES]{"insert", "update", "find hit", "find miss", "erase miss", "erase hit", "mixed"};

// What the timed loop does. Insert and update both call insert, hit and miss both call find / erase,
// so the loop only branches three ways. The finer split only matters when generating the stream.
enum class OpKind : std::uint8_t
{
    Insert, // insert + update
    Find,   // find hit + find miss
    Erase   // erase hit + erase miss
};

// Keys are stored by value (not as an index into Workload::keys) so the timed loops read them
// sequentially. An index would add a random read of the key array to every op, which is a cache
// miss that has nothing to do with the map being measured.
template <typename K>
struct Op
{
    OpKind kind;
    K key;
};

template <typename K>
struct Workload
{
    // keys[0, N)           present: inserted by the phases and pre-filled for mixed
    // keys[N, 2N)          absent: never inserted, used for every miss
    // keys[2N, 2N + N/4)   fresh: inserted for the first time by mixed
    std::vector<K> keys;
    std::vector<K> present_shuffled; // copies of the present keys, different order to insertion
    std::vector<Op<K>> mixed;        // N ops, replayed on a freshly filled map every pass
    std::size_t mixed_find_hits = 0; // how many mixed finds must return a value per pass
};

template <typename K>
Workload<K> make_workload(std::uint64_t seed)
{
    std::mt19937_64 rng{seed};

    constexpr std::size_t quarter = N / 4;
    constexpr std::size_t present_begin = 0, absent_begin = N, fresh_begin = 2 * N;

    Workload<K> w;
    {
        std::unordered_set<K> seen;
        w.keys.reserve(fresh_begin + quarter);
        while (w.keys.size() < fresh_begin + quarter)
        {
            K k = make_key<K>(rng());
            if (seen.insert(k).second)
                w.keys.push_back(std::move(k));
        }
    }

    w.present_shuffled.assign(w.keys.begin() + present_begin, w.keys.begin() + absent_begin);
    std::shuffle(w.present_shuffled.begin(), w.present_shuffled.end(), rng);

    // exact 25/25/25/25 split, finds and erases each split 50/50 hit/miss, in random order
    enum Gen : std::uint8_t
    {
        G_INSERT,
        G_UPDATE,
        G_FIND_HIT,
        G_FIND_MISS,
        G_ERASE_HIT,
        G_ERASE_MISS
    };
    std::vector<Gen> kinds;
    kinds.reserve(N);
    kinds.insert(kinds.end(), quarter, G_INSERT);
    kinds.insert(kinds.end(), quarter, G_UPDATE);
    kinds.insert(kinds.end(), quarter / 2, G_FIND_HIT);
    kinds.insert(kinds.end(), quarter - quarter / 2, G_FIND_MISS);
    kinds.insert(kinds.end(), quarter / 2, G_ERASE_HIT);
    kinds.insert(kinds.end(), quarter - quarter / 2, G_ERASE_MISS);
    std::shuffle(kinds.begin(), kinds.end(), rng);

    // simulate the map's contents so every op targets the right kind of key
    std::vector<std::size_t> live(N);
    for (std::size_t i = 0; i < N; ++i)
        live[i] = present_begin + i;
    std::size_t next_fresh = fresh_begin;
    std::uniform_int_distribution<std::size_t> absent_dist(absent_begin, fresh_begin - 1);

    auto random_live = [&]() -> std::size_t
    { return std::uniform_int_distribution<std::size_t>(0, live.size() - 1)(rng); };

    w.mixed.reserve(N);
    auto push = [&](OpKind kind, std::size_t idx)
    { w.mixed.push_back({kind, w.keys[idx]}); };

    for (Gen g : kinds)
    {
        switch (g)
        {
        case G_INSERT:
            live.push_back(next_fresh);
            push(OpKind::Insert, next_fresh++);
            break;
        case G_UPDATE:
            push(OpKind::Insert, live[random_live()]);
            break;
        case G_FIND_HIT:
            push(OpKind::Find, live[random_live()]);
            ++w.mixed_find_hits;
            break;
        case G_FIND_MISS:
            push(OpKind::Find, absent_dist(rng));
            break;
        case G_ERASE_HIT:
        {
            const std::size_t i = random_live();
            push(OpKind::Erase, live[i]);
            live[i] = live.back(); // swap-remove, order of live doesn't matter
            live.pop_back();
            break;
        }
        case G_ERASE_MISS:
            push(OpKind::Erase, absent_dist(rng));
            break;
        }
    }
    return w;
}

// ---------- running ----------

// Every pass time of one map, plus its correctness checks.
struct Samples
{
    std::array<std::vector<double>, NUM_PHASES> secs; // one entry per pass
    std::uint64_t checksum = 0;                       // sum of every value found, must match across maps
    bool mixed_hits_ok = true;                        // mixed finds hit exactly as often as expected
};

template <typename Fn>
double time_it(Fn fn)
{
    Timer t;
    fn();
    return t.elapsed();
}

// One pass of every phase on a map of type Map.
template <typename Map, typename K>
void run_pass(const Workload<K> &w, Samples &s)
{
    const auto &keys = w.keys;
    std::uint64_t &sum = s.checksum;

    {
        Map m;
        s.secs[INSERT].push_back(time_it([&]
                                         { for (std::size_t i = 0; i < N; ++i) map_insert(m, keys[i], i); }));
        s.secs[UPDATE].push_back(time_it([&]
                                         { for (std::size_t i = 0; i < N; ++i) map_insert(m, keys[i], i + 1); }));
        s.secs[FIND_HIT].push_back(time_it([&]
                                           { for (const K &k : w.present_shuffled)
                                                 if (const value_t *p = map_find(m, k)) sum += *p; }));
        s.secs[FIND_MISS].push_back(time_it([&]
                                            { for (std::size_t i = N; i < 2 * N; ++i)
                                                  if (const value_t *p = map_find(m, keys[i])) sum += *p; })); // never hits if the map is correct
        s.secs[ERASE_MISS].push_back(time_it([&]
                                             { for (std::size_t i = N; i < 2 * N; ++i) map_erase(m, keys[i]); }));
        s.secs[ERASE_HIT].push_back(time_it([&]
                                            { for (const K &k : w.present_shuffled) map_erase(m, k); }));
    }

    {
        Map m;
        for (std::size_t i = 0; i < N; ++i) // untimed setup
            map_insert(m, keys[i], i);

        std::size_t hits = 0;
        s.secs[MIXED].push_back(time_it([&]
                                        {
                                            value_t v = 0;
                                            for (const Op<K> &op : w.mixed)
                                            {
                                                switch (op.kind)
                                                {
                                                case OpKind::Insert:
                                                    map_insert(m, op.key, ++v);
                                                    break;
                                                case OpKind::Find:
                                                    if (const value_t *p = map_find(m, op.key))
                                                    {
                                                        sum += *p;
                                                        ++hits;
                                                    }
                                                    break;
                                                case OpKind::Erase:
                                                    map_erase(m, op.key);
                                                    break;
                                                }
                                            } }));
        s.mixed_hits_ok = s.mixed_hits_ok && hits == w.mixed_find_hits;
    }
}

// ---------- terminal output ----------

std::string fmt_duration(double secs) // 75.3 -> "1m 15s", 9.42 -> "9.4s"
{
    if (secs < 60)
        return std::format("{:.1f}s", secs);
    const int total = static_cast<int>(secs + 0.5);
    if (total < 3600)
        return std::format("{}m {:02}s", total / 60, total % 60);
    return std::format("{}h {:02}m {:02}s", total / 3600, total % 3600 / 60, total % 60);
}

std::string with_commas(std::size_t n) // 1000000 -> "1,000,000"
{
    std::string s = std::to_string(n);
    for (int i = static_cast<int>(s.size()) - 3; i > 0; i -= 3)
        s.insert(static_cast<std::size_t>(i), ",");
    return s;
}

// Runs pass_fn `passes` times, keeping a live progress line with elapsed time and an estimate of what's left.
template <typename PassFn>
void run_passes(const char *label, std::size_t passes, PassFn pass_fn)
{
    Timer t;
    for (std::size_t p = 0; p < passes; ++p)
    {
        pass_fn();
        const double elapsed = t.elapsed();
        const double left = elapsed / static_cast<double>(p + 1) * static_cast<double>(passes - p - 1);
        std::printf("\r  %-6s pass %3zu/%-3zu  %8s elapsed  ~%-8s left   ", label, p + 1, passes,
                    fmt_duration(elapsed).c_str(), fmt_duration(left).c_str());
        std::fflush(stdout);
    }
    std::printf("\r  %-6s %zu passes done in %-10s%30s\n", label, passes, fmt_duration(t.elapsed()).c_str(), "");
}

// ---------- results ----------

using Ns = std::array<double, NUM_PHASES>; // median ns per op, per phase

double median(std::vector<double> v)
{
    const std::size_t mid = v.size() / 2;
    std::nth_element(v.begin(), v.begin() + static_cast<std::ptrdiff_t>(mid), v.end());
    if (v.size() % 2)
        return v[mid];
    const double hi = v[mid];
    const double lo = *std::max_element(v.begin(), v.begin() + static_cast<std::ptrdiff_t>(mid));
    return (lo + hi) / 2;
}

Ns medians_ns(const Samples &s)
{
    Ns ns{};
    for (std::size_t p = 0; p < NUM_PHASES; ++p)
        ns[p] = median(s.secs[p]) * 1e9 / static_cast<double>(N); // every phase is N ops per pass
    return ns;
}

// Markdown table: one column per open_map, then unordered_map, then speedup (unordered_map / fastest open_map).
std::string make_table(const std::vector<std::string> &open_names, const std::vector<Ns> &open, const Ns &std_ns, Ns &speedup)
{
    std::string md = "| phase |";
    for (const std::string &name : open_names)
        md += std::format(" {} |", name);
    md += " unordered_map | speedup |\n|:--|";
    for (std::size_t i = 0; i < open.size() + 2; ++i)
        md += "--:|";
    md += "\n";

    for (std::size_t p = 0; p < NUM_PHASES; ++p)
    {
        std::size_t best = 0;
        for (std::size_t i = 1; i < open.size(); ++i)
            if (open[i][p] < open[best][p])
                best = i;

        md += std::format("| {} |", phase_names[p]);
        for (std::size_t i = 0; i < open.size(); ++i)
            md += i == best && open.size() > 1 ? std::format(" **{:.1f}** |", open[i][p]) : std::format(" {:.1f} |", open[i][p]);
        speedup[p] = std_ns[p] / open[best][p];
        md += std::format(" {:.1f} | {:.2f}x |\n", std_ns[p], speedup[p]);
    }
    return md + "\n";
}

struct Result
{
    std::string key_name;
    float lf;
    std::size_t ops;
    Ns speedup;        // unordered_map / open_map
    std::string table; // markdown
    bool ok;
};

template <typename K, float LF>
Result bench(const char *key_name, std::size_t ops)
{
    Timer total;
    std::printf("\n== %s ==\n", key_name);
    std::printf("  generating workload... ");
    std::fflush(stdout);
    Timer gen;
    const Workload<K> w = make_workload<K>(12345);
    std::printf("done in %s\n", fmt_duration(gen.elapsed()).c_str());

    Result res{key_name, LF, ops, {}, {}, true};

    const std::size_t passes = ops / N;
    std::printf("  lf %.2f vs unordered_map, %s ops per phase\n", LF, with_commas(ops).c_str());
    Samples s_open, s_std;
    run_passes("bench", passes, [&]
               {
                   run_pass<omap<K, LF>>(w, s_open);
                   run_pass<umap<K>>(w, s_std); });
    res.ok = s_open.checksum == s_std.checksum && s_open.mixed_hits_ok && s_std.mixed_hits_ok;

    res.table = std::format("### {} keys, lf {:.2f}, {} ops per phase ({} passes of {})\n\n",
                            key_name, LF, with_commas(ops), passes, with_commas(N));
    res.table += std::format("Correctness check: {}\n\n", res.ok ? "OK" : "**FAILED**");
    res.table += make_table({std::format("open_map (lf {:.2f})", LF)}, {medians_ns(s_open)},
                            medians_ns(s_std), res.speedup);

    std::printf("  speedup:");
    for (std::size_t p = 0; p < NUM_PHASES; ++p)
        std::printf("  %s %.2fx", phase_names[p], res.speedup[p]);
    std::printf("\n  %s done in %s%s\n", key_name, fmt_duration(total.elapsed()).c_str(),
                res.ok ? "" : "   CORRECTNESS CHECK FAILED");
    return res;
}

std::string build_markdown(const std::vector<Result> &results, double total_secs)
{
    char date[32];
    const std::time_t now = std::time(nullptr);
    std::strftime(date, sizeof date, "%Y-%m-%d %H:%M:%S", std::localtime(&now));

    std::string md = std::format("# open_map benchmark: {}\n\n", date);
    md += std::format("- Took: {}\n", fmt_duration(total_secs));
#ifdef __VERSION__
    md += std::format("- Compiler: {}\n", __VERSION__);
#endif
#ifdef __OPTIMIZE__
    md += "- Optimised build: yes\n";
#else
    md += "- Optimised build: **NO, these numbers are meaningless. Build with -O2.**\n";
#endif
#ifdef NDEBUG
    md += "- Asserts: off\n";
#else
    md += "- Asserts: on (build with -DNDEBUG)\n";
#endif
    md += std::format("- Map size: ~{} keys. Ops are repeated in passes of {} per phase; each time is the median pass.\n\n",
                      with_commas(N), with_commas(N));

    md += "Speedup = unordered_map time / open_map time. Above 1x means open_map is faster. **Bold** = open_map is slower.\n\n";
    md += "| keys | load factor | ops per phase |";
    for (const char *name : phase_names)
        md += std::format(" {} |", name);
    md += "\n|:--|--:|--:|";
    for (std::size_t p = 0; p < NUM_PHASES; ++p)
        md += "--:|";
    md += "\n";
    for (const Result &r : results)
    {
        md += std::format("| {} | {:.2f} | {} |", r.key_name, r.lf, with_commas(r.ops));
        for (double s : r.speedup)
            md += s < 1.0 ? std::format(" **{:.2f}x** |", s) : std::format(" {:.2f}x |", s);
        md += "\n";
    }

    md += "\nTime per operation in ns (median pass), lower is better.\n\n";
    for (const Result &r : results)
        md += r.table;
    return md + "---\n\n";
}

int main(int argc, char **argv)
{
    const std::string out_path = argc > 1 ? argv[1] : "open_map_benchmark_results.md";
    Timer total;

    std::vector<Result> results;
    results.push_back(bench<std::int32_t, BEST_LF_INT32>("int32_t", OPS_INTEGRAL));
    results.push_back(bench<std::int64_t, BEST_LF_INT64>("int64_t", OPS_INTEGRAL));
    results.push_back(bench<std::string, BEST_LF_STRING>("std::string", OPS_STRING));

    const double total_secs = total.elapsed();
    std::ofstream out{out_path, std::ios::app};
    if (!out)
    {
        std::fprintf(stderr, "could not open %s for writing\n", out_path.c_str());
        return 1;
    }
    out << build_markdown(results, total_secs);
    std::printf("\ntotal time: %s\nappended to %s\n", fmt_duration(total_secs).c_str(), out_path.c_str());
    return 0;
}
